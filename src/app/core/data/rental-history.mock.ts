/** Get rental history records for a specific area, sorted newest-first */
export function getRentalHistoryByAreaId(areaId: string): RentalHistory[] {
  return MOCK_RENTAL_HISTORY
    .filter(rh => rh.AREA_ID === areaId)
    .sort((a, b) => {
      const dateA = parseInt(a.LEASE_END.replace(/\/Date\((\d+)\)\//, '$1'));
      const dateB = parseInt(b.LEASE_END.replace(/\/Date\((\d+)\)\//, '$1'));
      return dateB - dateA; // Newest first
    });
}

/** Get rent-rate timeline for chart rendering */
export function getRentRateTimeline(areaId: string): { date: Date; rent: number }[] {
  const history = getRentalHistoryByAreaId(areaId);
  const timeline: { date: Date; rent: number }[] = [];

  history.forEach(rh => {
    const startTimestamp = parseInt(rh.LEASE_START.replace(/\/Date\((\d+)\)\//, '$1'));
    const endTimestamp = parseInt(rh.LEASE_END.replace(/\/Date\((\d+)\)\//, '$1'));

    timeline.push({ date: new Date(startTimestamp), rent: rh.MONTHLY_RENT });
    timeline.push({ date: new Date(endTimestamp), rent: rh.MONTHLY_RENT });
  });

  return timeline.sort((a, b) => a.date.getTime() - b.date.getTime());
}

/** Get unique area IDs that have rental history */
export function getAreaIdsWithHistory(): string[] {
  return [...new Set(MOCK_RENTAL_HISTORY.map(rh => rh.AREA_ID))];
}

/** Get summary per area */
export function getRentalSummaryByArea(): Record<string, {
  count: number;
  totalRevenue: number;
  avgMonthlyRent: number;
  avgOccupancyDays: number;
}> {
  const areaIds = getAreaIdsWithHistory();
  const summary: Record<string, any> = {};

  areaIds.forEach(areaId => {
    const records = MOCK_RENTAL_HISTORY.filter(rh => rh.AREA_ID === areaId);
    summary[areaId] = {
      count: records.length,
      totalRevenue: records.reduce((s, r) => s + r.TOTAL_REVENUE, 0),
      avgMonthlyRent: Math.round(records.reduce((s, r) => s + r.MONTHLY_RENT, 0) / records.length),
      avgOccupancyDays: Math.round(records.reduce((s, r) => s + r.OCCUPANCY_DAYS, 0) / records.length),
    };
  });

  return summary;
}
