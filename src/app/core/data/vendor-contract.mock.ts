export function computeVendorStats(contracts: VendorContract[]): VendorStats {
  const total = contracts.length;
  const expiring = contracts.filter(c => computeStatus(c) === 'Expiring').length;
  const expired = contracts.filter(c => computeStatus(c) === 'Expired').length;
  const totalValue = contracts.reduce((sum, c) => sum + c.value, 0);

  const expiringCritical = contracts.filter(c => {
    const s = computeStatus(c);
    return s === 'Expiring' && c.priority === 'Critical';
  }).length;

  const expiringWarning = contracts.filter(c => {
    const s = computeStatus(c);
    return s === 'Expiring' && c.priority !== 'Critical';
  }).length;

  return {
    totalContracts: total,
    expiringCount: expiring,
    expiredCount: expired,
    totalValue,
    expiringCritical,
    expiringWarning
  };
}
